const { Stack } = require('aws-cdk-lib');
const apigateway = require('aws-cdk-lib/aws-apigateway');
const lambda = require('aws-cdk-lib/aws-lambda');
const iam = require('aws-cdk-lib/aws-iam');
const dynamodb = require('aws-cdk-lib/aws-dynamodb');
const path = require('path');

class UserPreferencesStack extends Stack {
  constructor(scope, id, props) {
    super(scope, id, props);

    // Import the User Preferences DynamoDB table
    const userPreferencesTable = dynamodb.Table.fromTableArn(
      this,
      'ImportedUserPreferencesTable',
      props.userPreferencesTableArn
    );

    // Create Lambda function for user preferences
    const userPreferencesLambda = new lambda.Function(this, 'UserPreferencesFunction', {
      runtime: lambda.Runtime.PYTHON_3_12,
      handler: 'user_preferences_handler.handler',
      code: lambda.Code.fromAsset(path.join(__dirname, '../../MenuAnalysisAppServer/lambdas/menu')),
      environment: {
        USER_PREFERENCES_TABLE: userPreferencesTable.tableName,
      },
    });

    // Grant DynamoDB permissions to Lambda
    userPreferencesTable.grantReadWriteData(userPreferencesLambda);

    // Create API Gateway
    const api = new apigateway.RestApi(this, 'UserPreferencesApi', {
      restApiName: 'User Preferences API',
      defaultCorsPreflightOptions: {
        allowOrigins: apigateway.Cors.ALL_ORIGINS,
        allowMethods: apigateway.Cors.ALL_METHODS,
      },
    });

    // Add Gateway Responses so that API Gateway returns CORS headers
    // even for errors generated by the authorizer or by API Gateway itself
    const corsResponseHeaders = {
      'Access-Control-Allow-Origin': "'*'",
      'Access-Control-Allow-Headers': "'Content-Type,Authorization'",
      'Access-Control-Allow-Methods': "'OPTIONS,GET,PUT,DELETE'",
    };

    api.addGatewayResponse('UnauthorizedGatewayResponse', {
      type: apigateway.ResponseType.UNAUTHORIZED,
      responseHeaders: corsResponseHeaders,
    });

    api.addGatewayResponse('AccessDeniedGatewayResponse', {
      type: apigateway.ResponseType.ACCESS_DENIED,
      responseHeaders: corsResponseHeaders,
    });

    api.addGatewayResponse('Default4xxGatewayResponse', {
      type: apigateway.ResponseType.DEFAULT_4XX,
      responseHeaders: corsResponseHeaders,
    });

    api.addGatewayResponse('Default5xxGatewayResponse', {
      type: apigateway.ResponseType.DEFAULT_5XX,
      responseHeaders: corsResponseHeaders,
    });

    // Create API Gateway Cognito Authorizer
    const authorizer = new apigateway.CognitoUserPoolsAuthorizer(this, 'UserPreferencesAuthorizer', {
      cognitoUserPools: [props.userPool],
    });

    // Create API resources and methods
    const preferences = api.root.addResource('preferences');
    
    // GET /preferences - Get all user preferences
    preferences.addMethod('GET', new apigateway.LambdaIntegration(userPreferencesLambda), {
      authorizer: authorizer,
      authorizationType: apigateway.AuthorizationType.COGNITO,
    });

    // Create dietary preferences resource
    const dietaryPrefs = preferences.addResource('dietary');
    
    // PUT /preferences/dietary - Update dietary preferences (allergens and restrictions)
    dietaryPrefs.addMethod('PUT', new apigateway.LambdaIntegration(userPreferencesLambda), {
      authorizer: authorizer,
      authorizationType: apigateway.AuthorizationType.COGNITO,
    });

    // DELETE /preferences/dietary - Remove dietary preferences
    dietaryPrefs.addMethod('DELETE', new apigateway.LambdaIntegration(userPreferencesLambda), {
      authorizer: authorizer,
      authorizationType: apigateway.AuthorizationType.COGNITO,
    });

    // Create restaurants resource
    const restaurants = preferences.addResource('restaurants');
    
    // PUT /preferences/restaurants - Update saved restaurants
    restaurants.addMethod('PUT', new apigateway.LambdaIntegration(userPreferencesLambda), {
      authorizer: authorizer,
      authorizationType: apigateway.AuthorizationType.COGNITO,
    });

    // DELETE /preferences/restaurants - Remove saved restaurants
    restaurants.addMethod('DELETE', new apigateway.LambdaIntegration(userPreferencesLambda), {
      authorizer: authorizer,
      authorizationType: apigateway.AuthorizationType.COGNITO,
    });
  }
}

module.exports = { UserPreferencesStack };